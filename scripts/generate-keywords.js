#!/usr/bin/env node
// Regenerates the EXTRA_KEYWORDS block at the bottom of emojify.js from:
//   - emojilib (keywords for each emoji character)    https://github.com/muan/emojilib
//   - emoji-datasource (Slack's emoji short names)    https://github.com/iamcal/emoji-data
// Both are MIT licensed. Run: node scripts/generate-keywords.js

const fs = require('fs');
const path = require('path');

const EMOJILIB_URL = 'https://cdn.jsdelivr.net/npm/emojilib@4.0.3/dist/emoji-en-US.json';
const DATASOURCE_URL = 'https://cdn.jsdelivr.net/npm/emoji-datasource@16.0.0/emoji.json';

// Newer emoji may not exist in Slack yet, so stay a few Unicode versions back.
const MAX_UNICODE_VERSION = 14.0;
// Keywords shared by more emoji than this are too generic ("face", "animal").
const MAX_EMOJI_PER_KEYWORD = 6;
const MIN_KEYWORD_LENGTH = 3;
const STOPWORDS = new Set(
  `the and for you your are was were with that this these those have has had not but all can get got
  just like one two out our its too very some any more most make made take into onto from than then
  them they their there here what when where which who why how also only over under upon off big small
  little use used other open close closed mouth eye eyes face human person people man men woman women
  male female boy girl sign symbol nature object objects thing things white black red blue green yellow
  orange purple brown pink grey gray dark light square circle round shape button blue-square word
  letter letters number numbers country nation flag banner great feature desk full keep heading next`.split(/\s+/)
);

const toChar = (unified) => unified.split('-').map((h) => String.fromCodePoint(parseInt(h, 16))).join('');
const stripVS = (s) => s.replace(/\uFE0F/g, '');

async function main() {
  const [emojilib, datasource] = await Promise.all(
    [EMOJILIB_URL, DATASOURCE_URL].map((url) => fetch(url).then((r) => r.json()))
  );

  const slackByChar = new Map();
  for (const d of datasource) {
    if (parseFloat(d.added_in) > MAX_UNICODE_VERSION) continue;
    if (/^u[0-9a-f]{4}$/.test(d.short_name)) continue; // Japanese sign buttons like :u55b6:
    slackByChar.set(stripVS(toChar(d.unified)), d.short_name);
  }

  // keyword -> Set of Slack names
  const emojiByKeyword = new Map();
  for (const [char, keywords] of Object.entries(emojilib)) {
    const name = slackByChar.get(stripVS(char));
    if (!name) continue;
    for (const raw of keywords) {
      const keyword = raw.toLowerCase().replace(/[_-]+/g, ' ').trim();
      if (!/^[a-z0-9]+( [a-z0-9]+){0,2}$/.test(keyword)) continue;
      if (keyword.length < MIN_KEYWORD_LENGTH || STOPWORDS.has(keyword)) continue;
      if (!emojiByKeyword.has(keyword)) emojiByKeyword.set(keyword, new Set());
      emojiByKeyword.get(keyword).add(name);
    }
  }

  // Flip back to emoji -> keywords, dropping generic keywords
  const keywordsByEmoji = new Map();
  for (const [keyword, names] of emojiByKeyword) {
    if (names.size > MAX_EMOJI_PER_KEYWORD) continue;
    for (const name of names) {
      if (!keywordsByEmoji.has(name)) keywordsByEmoji.set(name, []);
      keywordsByEmoji.get(name).push(keyword.replace(/ /g, '_'));
    }
  }

  const lines = [...keywordsByEmoji]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, keywords]) => `  ${/^[a-z_][a-z0-9_]*$/.test(name) ? name : `'${name}'`}: '${keywords.join(' ')}',`);

  const file = path.join(__dirname, '..', 'emojify.js');
  const source = fs.readFileSync(file, 'utf8');
  const start = '// <generated-keywords>';
  const end = '// </generated-keywords>';
  const block = `${start}\n// Generated by scripts/generate-keywords.js. Do not edit by hand.\nconst EXTRA_KEYWORDS = {\n${lines.join('\n')}\n};\n${end}`;
  const pattern = new RegExp(`${start}[\\s\\S]*${end}`);
  if (!pattern.test(source)) throw new Error(`Missing ${start} markers in emojify.js`);
  fs.writeFileSync(file, source.replace(pattern, block));

  const keywordCount = [...keywordsByEmoji.values()].reduce((n, keywords) => n + keywords.length, 0);
  console.log(`Wrote ${lines.length} emoji / ${keywordCount} keywords to emojify.js`);
}

main();
