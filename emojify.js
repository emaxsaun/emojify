// How often a hand-picked emoji wins over a random one for the same word
const CURATED_CHANCE = 0.75;

// Words that set the mood emoji added to the end of a described message
const POSITIVE_WORDS = new Set(
  `happy glad love great awesome amazing yay congrats congratulations win won nice thanks thank good
  excited fun best perfect cool shipped done fixed celebrate party lol haha yes welcome beautiful`.split(/\s+/)
);
const NEGATIVE_WORDS = new Set(
  `sad hate broken fail failed failing bad worst ugh tired stuck sick angry annoyed bug bugs outage
  terrible awful problem issue issues late no never down cry crying exhausted meetings monday`.split(/\s+/)
);
const MOODS = {
  positive: ['tada', 'sparkles', 'raised_hands', 'star-struck', 'partying_face', 'muscle'],
  negative: ['skull', 'sob', 'melting_face', 'face_palm', 'upside_down_face', 'weary'],
  question: ['thinking_face', 'face_with_monocle', 'eyes'],
};

const pickRandom = (items) => items[Math.floor(Math.random() * items.length)];

// keyword (phrases joined by spaces) -> { curated: emoji name, extra: [emoji names] }
let keywordIndex;
function getKeywordIndex() {
  if (keywordIndex) return keywordIndex;
  keywordIndex = new Map();
  const add = (source, type) => {
    for (const [emoji, keywords] of Object.entries(source)) {
      for (const keyword of keywords.split(/\s+/).filter(Boolean)) {
        const key = keyword.replace(/_/g, ' ');
        if (!keywordIndex.has(key)) keywordIndex.set(key, { extra: [] });
        const entry = keywordIndex.get(key);
        if (type === 'curated') entry.curated = emoji;
        else if (emoji !== entry.curated) entry.extra.push(emoji);
      }
    }
  };
  add(EMOJI_KEYWORDS, 'curated');
  add(EXTRA_KEYWORDS, 'extra');
  return keywordIndex;
}

function parseArgs(argv) {
  const opts = { color: 'white', copy: true, words: [] };
  for (const arg of argv) {
    if (arg === '-y' || arg === '--yellow') opts.color = 'yellow';
    else if (arg === '-w' || arg === '--white') opts.color = 'white';
    else if (arg === '-m' || arg === '--mix') opts.color = 'mix';
    else if (arg === '-d' || arg === '--describe') opts.describe = true;
    else if (arg === '--no-copy') opts.copy = false;
    else if (arg === '-h' || arg === '--help') opts.help = true;
    else opts.words.push(arg);
  }
  return opts;
}

function emojify(message, color) {
  let i = 0;
  return message
    .split('\n')
    .map((line) =>
      line
        .trim()
        .split(/\s+/)
        .map((word) =>
          [...word]
            .map((ch) => {
              const lower = ch.toLowerCase();
              const name = /[a-z]/.test(lower) ? lower : SYMBOLS[ch];
              if (!name) return ch; // digits, punctuation, etc. pass through
              const c = color === 'mix' ? (i++ % 2 ? 'yellow' : 'white') : color;
              return `:alphabet-${c}-${name}:`;
            })
            .join('')
        )
        .join(WORD_GAP)
    )
    .join('\n');
}

// Word forms to try, most specific first: "parties" -> "party", "coding" -> "code".
function stems(word) {
  const forms = [word];
  const strip = (suffix, ...replacements) => {
    if (word.length <= suffix.length + 2 || !word.endsWith(suffix)) return;
    const base = word.slice(0, -suffix.length);
    forms.push(base, ...replacements.map((r) => base + r));
    if (/([b-df-hj-np-tv-z])\1$/.test(base)) forms.push(base.slice(0, -1)); // shipping -> ship
  };
  strip('ies', 'y');
  strip('es');
  strip('s');
  strip('ing', 'e');
  strip('ed', 'e');
  return forms;
}

// Picks an emoji for a word or phrase: usually the hand-picked one, sometimes a random alternative.
function lookup(words) {
  const index = getKeywordIndex();
  const forms = words.length > 1 ? [words.join(' ')] : stems(words[0]);
  const entry = forms.map((form) => index.get(form)).find(Boolean);
  if (!entry) return;
  if (entry.curated && (!entry.extra.length || Math.random() < CURATED_CHANCE)) return entry.curated;
  return pickRandom(entry.extra);
}

function moodOf(message, words) {
  if (message.trim().endsWith('?')) return 'question';
  let score = 0;
  for (const word of words) {
    if (POSITIVE_WORDS.has(word)) score++;
    if (NEGATIVE_WORDS.has(word)) score--;
  }
  if (score > 0) return 'positive';
  if (score < 0) return 'negative';
}

function describe(message) {
  const allWords = [];
  const lines = message.split('\n').map((line) => {
    const words = line.toLowerCase().replace(/['’]/g, '').match(/[a-z0-9+]+/g) || [];
    allWords.push(...words);
    const emojis = [];
    for (let i = 0; i < words.length; ) {
      let matched = false;
      // Prefer the longest phrase starting here ("good morning" over "good")
      for (let len = Math.min(MAX_PHRASE_WORDS, words.length - i); len > 0; len--) {
        const emoji = lookup(words.slice(i, i + len));
        if (emoji) {
          if (emojis[emojis.length - 1] !== emoji) emojis.push(emoji);
          i += len;
          matched = true;
          break;
        }
      }
      if (!matched) i++;
    }
    return emojis;
  });

  // End on an emoji that sums up the vibe
  const nonEmpty = lines.filter((emojis) => emojis.length);
  const mood = moodOf(message, allWords);
  if (mood && nonEmpty.length) {
    const last = nonEmpty[nonEmpty.length - 1];
    const options = MOODS[mood].filter((e) => !last.includes(e));
    if (options.length) last.push(pickRandom(options));
  }

  return nonEmpty.map((emojis) => emojis.map((e) => `:${e}:`).join('')).join('\n');
}

function copyToClipboard(text) {
  const cmd =
    process.platform === 'darwin'
      ? 'pbcopy'
      : process.platform === 'win32'
        ? 'clip'
        : 'xclip -selection clipboard';
  try {
    execSync(cmd, { input: text });
    return true;
  } catch {
    return false;
  }
}

function prompt(question) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  return new Promise((resolve) =>
    rl.question(question, (answer) => {
      rl.close();
      resolve(answer);
    })
  );
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) {
    console.log('Usage: emojify [-w|-y|-m|-d] [--no-copy] [message]');
    return;
  }

  const message = opts.words.length
    ? opts.words.join(' ')
    : await prompt('Message: ');
  if (!message.trim()) return;

  const output = opts.describe ? describe(message) : emojify(message, opts.color);
  if (!output) {
    console.log('🤷 No emoji matches for that message.');
    process.exitCode = 1;
    return;
  }
  console.log(`\n${output}\n`);
  if (opts.copy) {
    console.log(copyToClipboard(output) ? '📋 Copied to clipboard — paste into Slack.' : '⚠️  Could not copy to clipboard.');
  }
}

